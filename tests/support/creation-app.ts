import { join } from "node:path";
import { randomUUID } from "node:crypto";
import type {
  ApplicationToolEngine,
  ApplicationRunCallbacks,
  ApplicationRunScope,
} from "../../src/shared/engine/application-tools.js";
import type { CreationTaskView, CreationAvailability } from "../../src/shared/creation/contracts.js";
import type { Route } from "../../src/server/http/router.js";
import { projectFileApiFixture } from "./project-file-api-fixture.js";
import { createSkillFeature } from "../../src/server/skills/integration/feature.js";
import { createCreationFeature } from "../../src/server/creation/integration/feature.js";
import { CreationProfiles } from "../../src/server/creation/integration/profiles.js";
import { richDocumentFromMarkdown } from "../../src/server/documents/rich-codec.js";
import { CreationError } from "../../src/server/creation/contracts.js";

type RunInput = Parameters<ApplicationToolEngine["run"]>[0];
export type CreationTestHandler = (
  input: RunInput,
  callbacks: ApplicationRunCallbacks,
  scope: ApplicationRunScope,
) => Promise<void>;
export async function creationAppFixture() {
  const routes: Route[] = [],
    files = await projectFileApiFixture({ extraRoutes: routes }),
    root = join(files.assetRoot, "creation-application");
  let actor = "operator:test-user",
    runs = 0,
    profileModel = "original-model";
  const skills = await createSkillFeature({ stateRoot: root, version: "0.0.18", owner: () => actor }),
    scopes: {
      profileModel: string | undefined;
      scope: ApplicationRunScope;
      callbacks: ApplicationRunCallbacks;
      input: RunInput;
    }[] = [];
  async function save(
    callbacks: ApplicationRunCallbacks,
    scope: ApplicationRunScope,
    text = "Generated by the actual application tool.",
  ) {
    return callbacks.call({
      ...scope,
      callId: randomUUID(),
      name: "panda_documents_create",
      arguments: {
        title: "An editable result",
        body: richDocumentFromMarkdown("## A clear result\n\n" + text),
      },
    });
  }
  let handler: CreationTestHandler = async (_input, callbacks, scope) => {
    await save(callbacks, scope);
  };
  const open = () => {
    const profiles = new CreationProfiles(
      {
        enabled: true,
        invalid: false,
        defaultProfileId: "codex",
        profiles: [{ id: "codex", engineId: "codex", model: profileModel }],
      },
      new Set(["codex"]),
      async () => "unused",
    );
    return createCreationFeature({
      stateRoot: root,
      owner: () => actor,
      authorize: async (_owner, project) => {
        if (!files.grants.has(project)) throw new CreationError("notFound");
      },
      documents: files.application().navigation,
      skills: skills.catalog,
      profiles,
      concurrency: 1,
      engines: {
        select(profile) {
          return {
            id: "codex",
            async run(input, callbacks) {
              const scope = { sessionId: "session-" + ++runs, runId: "run-" + runs };
              scopes.push({ profileModel: profile.model, scope, callbacks, input });
              await callbacks.started(scope);
              await handler(input, callbacks, scope);
              return { ...scope, status: "completed" };
            },
          };
        },
      },
    });
  };
  let feature = open();
  routes.push(...skills.routes, ...feature.routes);
  feature.start();
  return {
    files,
    scopes,
    save,
    root,
    onRun(value: CreationTestHandler) {
      handler = value;
    },
    actor(value: string) {
      actor = value;
    },
    runs: () => runs,
    changeProfile(value: string) {
      profileModel = value;
    },
    async create(prompt: string) {
      const options = await files.call("/api/document-creations/options"),
        availability = options.body as CreationAvailability;
      const request = {
        id: randomUUID(),
        projectId: "project-1",
        treeVersion: 0,
        parentId: null,
        locale: "en",
        prompt,
        profileId: "codex",
        selections: [availability.defaultWorkflow!],
      };
      return { request, response: await files.call("/api/document-creations", "POST", request) };
    },
    async task(id: string) {
      const response = await files.call("/api/document-creations/detail?" + new URLSearchParams({ id }));
      if (response.status !== 200) throw new Error("Task read failed: " + response.status);
      return response.body.task as CreationTaskView;
    },
    async until(id: string, predicate: (task: CreationTaskView) => boolean) {
      const deadline = Date.now() + 30000;
      for (;;) {
        const task = await this.task(id);
        if (predicate(task)) return task;
        if (Date.now() > deadline) throw new Error("Creation task did not settle: " + task.state);
        await Bun.sleep(50);
      }
    },
    async restart() {
      await feature.close();
      files.reopen();
      feature = open();
      routes.splice(0, routes.length, ...skills.routes, ...feature.routes);
      feature.start();
    },
    async close() {
      await feature.close();
      skills.close();
      await files.close();
    },
  };
}
