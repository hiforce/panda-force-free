type Fixture = Awaited<ReturnType<typeof creationAppFixture>>;
async function edit(f: Fixture, id: string, content: string, save = true) {
  const application = f.files.application(),
    snapshot = await application.queries.editor("project-1", id);
  await application.editor.autosave("operator:test-user", "project-1", id, {
    operationId: randomUUID(),
    version: snapshot.draft.version,
    baseRevisionId: snapshot.saved.revision.id,
    working: {
      title: "Manually refined title",
      locale: "en",
      content: "",
      resources: snapshot.saved.revision.resources || [],
      body: richDocumentFromMarkdown(content),
    },
  });
  if (save) {
    const current = await application.queries.editor("project-1", id);
    await application.editor.save("operator:test-user", "project-1", id, {
      operationId: randomUUID(),
      draftVersion: current.draft.version,
      revisionId: current.saved.revision.id,
    });
  }
}
async function context(callbacks: ApplicationRunCallbacks, scope: ApplicationRunScope) {
  const call = async (args: Record<string, unknown>) =>
    JSON.parse(
      (await callbacks.call({ ...scope, callId: randomUUID(), name: "panda_creation_context", arguments: args })).text,
    );
  let page = await call({}),
    text = page.text || "";
  if (page.text) {
    while (page.nextOffset !== null) {
      page = await call({ contextOffset: page.nextOffset });
      text += page.text;
    }
    page = JSON.parse(text);
  }
  let document;
  if (page.previousDocument) {
    let text = "",
      offset = 0;
    for (;;) {
      const next = await call({ documentOffset: offset });
      text += next.text;
      if (next.nextOffset === null) break;
      offset = next.nextOffset;
    }
    document = JSON.parse(text);
  }
  const full = [];
  for (const message of page.messages) {
    let text = message.excerpt,
      offset = message.nextOffset;
    while (offset !== null) {
      const next = await call({ messageId: message.id, offset });
      text += next.text;
      offset = next.nextOffset;
    }
    full.push(text);
  }
  return { ...page, full, document };
}
test("continuing reads the latest manually saved source, retains document identity and title, and replays one revision", async () => {
  const f = await creationAppFixture();
  try {
    const first = await f.create("Write the original requirements"),
      original = await f.until(first.request.id, (task) => task.state === "succeeded");
    const id = original.artifact!.documentId,
      firstRevision = (await f.files.application().queries.detail("project-1", id)).revision;
    const filename = original.artifact!.file!.path;
    expect(dirname(filename)).toBe(f.scopes[0]!.callbacks.directory!.path);
    expect(await readFile(filename, "utf8")).toContain("Generated by the actual application tool");
    await edit(f, id, "Manual section that the continuation must retain.");
    f.onRun(async (input, callbacks, scope) => {
      expect(input.prompt).toContain("Manual section");
      expect(input.prompt).toContain("Manually refined title");
      await context(callbacks, scope);
      expect(
        (
          await f.save(
            callbacks,
            scope,
            "Manual section that the continuation must retain.\n\nNew acceptance criteria.",
          )
        ).success,
      ).toBe(true);
    });
    const request = { taskId: original.id, id: randomUUID(), prompt: "Add acceptance criteria." };
    expect((await f.files.call("/api/document-creations/follow-up", "POST", request)).status).toBe(202);
    const updated = await f.until(request.id, (task) => task.state === "succeeded");
    expect(updated.artifact).toMatchObject({ documentId: id, title: "Manually refined title", revision: 3 });
    expect(updated.artifact!.file!.path).toBe(filename);
    expect(f.scopes.at(-1)!.callbacks.directory!.path).toBe(dirname(filename));
    expect(await readFile(filename, "utf8")).toContain("New acceptance criteria");
    expect((await readFile(filename, "utf8")).startsWith("# Manually refined title\n")).toBe(true);
    expect((await readdir(dirname(filename))).filter((name) => name.endsWith(".md"))).toHaveLength(1);
    expect(updated.document).toMatchObject({ documentId: id, title: "Manually refined title", revision: 3 });
    expect((await f.files.application().navigation.tree("project-1")).nodes).toHaveLength(1);
    const current = await f.files.application().queries.detail("project-1", id);
    expect(current.revision.content).toContain("New acceptance criteria");
    expect(await f.files.application().queries.revision("project-1", id, firstRevision.id)).toEqual(firstRevision);
    await f.restart();
    expect((await f.files.call("/api/document-creations/follow-up", "POST", request)).body.task.id).toBe(request.id);
    expect((await f.files.application().queries.detail("project-1", id)).document.revision).toBe(3);
    expect(await readFile(filename, "utf8")).toContain("New acceptance criteria");
  } finally {
    await f.close();
  }
}, 60000);

