test("concurrent manual edits stop a stale save; explicit recovery keeps all accepted text and updates the same document", async () => {
  const f = await creationAppFixture(),
    ready = Promise.withResolvers<void>(),
    proceed = Promise.withResolvers<void>();
  try {
    const first = await f.create("Original requirements"),
      original = await f.until(first.request.id, (task) => task.state === "succeeded");
    const id = original.artifact!.documentId,
      addition = "Keep the complete supplemental requirements. ".repeat(900);
    f.onRun(async (_input, callbacks, scope) => {
      ready.resolve();
      await proceed.promise;
      await context(callbacks, scope);
      await f.save(callbacks, scope, "This stale output must never overwrite the manual edit.");
    });
    const request = { taskId: original.id, id: randomUUID(), prompt: "Add validation rules" };
    expect((await f.files.call("/api/document-creations/message", "POST", request)).status).toBe(202);
    await ready.promise;
    expect(
      (
        await f.files.call("/api/document-creations/message", "POST", {
          taskId: request.id,
          id: randomUUID(),
          prompt: addition,
          selections: [],
        })
      ).status,
    ).toBe(202);
    await edit(f, id, "Latest manual corrections must be retained.");
    proceed.resolve();
    const blocked = await f.until(request.id, (task) => task.failure === "targetChanged");
    expect(blocked.artifact).toBeNull();
    expect((await f.files.application().queries.detail("project-1", id)).revision.content).toContain(
      "Latest manual corrections",
    );
    f.onRun(async (input, callbacks, scope) => {
      expect(input.prompt).toContain("Latest manual corrections");
      expect(input.prompt).toContain(request.prompt);
      expect((await f.save(callbacks, scope, "Premature save")).success).toBe(false);
      const updates = await context(callbacks, scope);
      expect(updates.full).toContain(addition);
      expect(
        (
          await f.save(
            callbacks,
            scope,
            "Latest manual corrections must be retained.\n\nValidation rules and complete supplemental requirements.",
          )
        ).success,
      ).toBe(true);
    });
    const operationId = randomUUID(),
      retry = { id: request.id, operationId };
    const result = await f.files.call("/api/document-creations/retry", "POST", retry);
    expect(result.status).toBe(200);
    expect(result.body.task.id).toBe(operationId);
    const recovered = await f.until(operationId, (task) => task.state === "succeeded");
    expect(recovered.artifact).toMatchObject({ documentId: id, revision: 3 });
    expect((await f.files.call("/api/document-creations/retry", "POST", retry)).body.task.id).toBe(operationId);
    expect((await f.files.application().queries.detail("project-1", id)).document.revision).toBe(3);
    expect((await f.files.application().navigation.tree("project-1")).nodes).toHaveLength(1);
    f.actor("operator:other");
    expect((await f.files.call("/api/document-creations/retry", "POST", retry)).status).toBe(404);
  } finally {
    proceed.resolve();
    await f.close();
  }
}, 60000);

test("a large saved document is read through bounded pages before continuation can save", async () => {
  const f = await creationAppFixture(),
    source = "Detailed existing requirement. ".repeat(10000);
  try {
    f.onRun(async (_input, callbacks, scope) => {
      await f.save(callbacks, scope, source);
    });
    const first = await f.create("Write complete source"),
      original = await f.until(first.request.id, (task) => task.state === "succeeded");
    f.onRun(async (input, callbacks, scope) => {
      expect(Buffer.byteLength(input.prompt)).toBeLessThan(131072);
      expect((await f.save(callbacks, scope, "Unread overwrite")).success).toBe(false);
      const result = await context(callbacks, scope);
      expect(JSON.stringify(result.document.document.body)).toContain(source);
      expect((await f.save(callbacks, scope, source + "\n\nNew criteria")).success).toBe(true);
    });
    const request = { id: randomUUID(), taskId: original.id, prompt: "Append new criteria" };
    expect((await f.files.call("/api/document-creations/message", "POST", request)).status).toBe(202);
    const saved = await f.until(request.id, (task) => task.state === "succeeded");
    expect(saved.artifact).toMatchObject({ documentId: original.artifact!.documentId, revision: 2 });
    expect(
      (await f.files.application().queries.detail("project-1", saved.artifact!.documentId)).revision.content,
    ).toContain(source);
  } finally {
    await f.close();
  }
}, 60000);

test("continuation retains original image bytes and historical revisions while rejecting foreign image references", async () => {
  const f = await creationAppFixture();
  try {
    const first = await f.create("Original"),
      original = await f.until(first.request.id, (task) => task.state === "succeeded"),
      id = original.artifact!.documentId,
      imageId = randomUUID();
    const bytes = await sharp({ create: { width: 4, height: 3, channels: 3, background: "#408080" } })
      .png()
      .toBuffer();
    const upload =
      "/api/project-documents/assets?" +
      new URLSearchParams({ project: "project-1", document: id, operationId: imageId, name: "original.png" });
    expect((await f.files.raw(upload, "POST", bytes)).status).toBe(201);
    const application = f.files.application(),
      opened = await application.queries.editor("project-1", id),
      body = richDocumentFromMarkdown("Original illustrated requirements");
    body.document.content!.push({
      type: "image",
      attrs: { src: "/api/document-assets/content?id=" + imageId, alt: "Original diagram", title: "" },
    });
    await application.editor.autosave("operator:test-user", "project-1", id, {
      operationId: randomUUID(),
      version: opened.draft.version,
      baseRevisionId: opened.saved.revision.id,
      working: { title: "With original diagram", locale: "en", content: "", resources: [], body },
    });
    const draft = await application.queries.editor("project-1", id);
    await application.editor.save("operator:test-user", "project-1", id, {
      operationId: randomUUID(),
      draftVersion: draft.draft.version,
      revisionId: draft.saved.revision.id,
    });
    const illustrated = await application.queries.detail("project-1", id);
    f.onRun(async (input, callbacks, scope) => {
      expect(input.prompt).toContain(imageId);
      await context(callbacks, scope);
      const revised = structuredClone(body);
      revised.document.content!.push(...richDocumentFromMarkdown("Additional acceptance criteria").document.content!);
      const call = (body: typeof revised) =>
        callbacks.call({
          ...scope,
          callId: randomUUID(),
          name: "panda_documents_create",
          arguments: { title: "Illustrated result", body },
        });
      const foreign = structuredClone(revised);
      foreign.document.content!.push({
        type: "image",
        attrs: { src: "/api/document-assets/content?id=" + randomUUID() },
      });
      expect((await call(foreign)).success).toBe(false);
      expect((await call(revised)).success).toBe(true);
    });
    const request = {
      id: randomUUID(),
      taskId: original.id,
      prompt: "Add acceptance criteria and keep the original diagram",
    };
    expect((await f.files.call("/api/document-creations/message", "POST", request)).status).toBe(202);
    const saved = await f.until(request.id, (task) => task.state === "succeeded");
    expect(saved.artifact).toMatchObject({ documentId: id, revision: 3 });
    const markdown = await readFile(saved.artifact!.file!.path, "utf8"),
      relative = markdown.match(/\]\((creation-assets-[a-f0-9-]+\/[a-f0-9]+\.png)\)/)?.[1];
    expect(relative).toBeTruthy();
    expect(markdown).not.toContain("/api/document-assets/");
    expect(await readFile(join(dirname(saved.artifact!.file!.path), relative!))).toEqual(bytes);
    expect(JSON.stringify((await application.queries.detail("project-1", id)).revision.body)).toContain(imageId);
    expect(await application.queries.revision("project-1", id, illustrated.revision.id)).toEqual(illustrated.revision);
    const image = await f.files.raw(
      "/api/project-documents/assets/content?" + new URLSearchParams({ project: "project-1", id: imageId }),
    );
    expect(Buffer.from(await image.arrayBuffer())).toEqual(bytes);
  } finally {
    await f.close();
  }
}, 60000);
