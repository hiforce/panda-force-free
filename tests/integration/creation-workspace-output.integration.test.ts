import { expect, test } from "bun:test";
import { randomUUID } from "node:crypto";
import { readFile, readdir, rm, unlink, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { creationAppFixture } from "../support/creation-app.js";
import { creationDocumentFilename } from "../../src/server/creation/integration/authored-files.js";

test("an occupied filename cannot complete a goal; restart and explicit retry export the same saved primary without rerunning the engine", async () => {
  const f = await creationAppFixture(),
    ready = Promise.withResolvers<void>(),
    proceed = Promise.withResolvers<void>();
  let occupied = "";
  try {
    f.onRun(async (_input, callbacks, scope) => {
      ready.resolve();
      await proceed.promise;
      await callbacks.call({ ...scope, callId: randomUUID(), name: "panda_creation_context", arguments: {} });
      const directory = callbacks.directory!;
      const marker = JSON.parse(await readFile(join(directory.path, ".panda-creation.json"), "utf8"));
      occupied = join(directory.path, creationDocumentFilename("An editable result", marker.conversationId));
      await writeFile(occupied, "User-owned source", { flag: "wx" });
      await f.save(callbacks, scope);
    });
    const first = await f.create("Generate a portable document");
    await ready.promise;
    expect(
      (
        await f.files.call("/api/document-creations/goal", "POST", {
          taskId: first.request.id,
          id: randomUUID(),
          action: "create",
          objective: "Save the actual document and its portable file",
        })
      ).status,
    ).toBe(200);
    proceed.resolve();
    const blocked = await f.until(first.request.id, (task) => task.failure === "fileChanged");
    expect(blocked.goal?.status).not.toBe("completed");
    expect(blocked.artifact).toBeNull();
    expect(blocked.state).toBe("committing");
    expect(await readFile(occupied, "utf8")).toBe("User-owned source");
    const nodes = (await f.files.application().navigation.tree("project-1")).nodes;
    expect(nodes).toHaveLength(1);
    const id = nodes[0]!.documentId,
      before = await f.files.application().queries.detail("project-1", id);
    await f.restart();
    expect((await f.task(first.request.id)).artifact).toBeNull();
    await unlink(occupied);
    const retry = { id: first.request.id, operationId: randomUUID() };
    expect((await f.files.call("/api/document-creations/retry", "POST", retry)).status).toBe(200);
    const saved = await f.until(first.request.id, (task) => task.state === "succeeded");
    expect(saved.artifact).toMatchObject({ documentId: id, file: { path: occupied, format: "markdown" } });
    expect(saved.goal?.status).toBe("completed");
    expect(await readFile(occupied, "utf8")).toContain("Generated by the actual application tool");
    expect(await f.files.application().queries.detail("project-1", id)).toEqual(before);
    expect(f.runs()).toBe(1);
    expect((await readdir(dirname(occupied))).filter((name) => name.endsWith(".md"))).toHaveLength(1);
    expect((await f.files.call("/api/document-creations/retry", "POST", retry)).body.task.id).toBe(saved.id);
    f.actor("operator:other");
    expect((await f.files.call("/api/document-creations/detail?id=" + saved.id)).status).toBe(404);
  } finally {
    proceed.resolve();
    await f.close();
  }
}, 60000);

test("manual conversation file edits stop the next round before changing its saved application document", async () => {
  const f = await creationAppFixture();
  try {
    const first = await f.create("First document"),
      original = await f.until(first.request.id, (task) => task.state === "succeeded"),
      path = original.artifact!.file!.path,
      id = original.artifact!.documentId,
      before = await f.files.application().queries.detail("project-1", id);
    await writeFile(path, "Manual filesystem corrections");
    const request = { taskId: original.id, id: randomUUID(), prompt: "Add acceptance criteria" };
    expect((await f.files.call("/api/document-creations/message", "POST", request)).status).toBe(202);
    const blocked = await f.until(request.id, (task) => task.failure === "fileChanged");
    expect(blocked.artifact).toBeNull();
    expect(await readFile(path, "utf8")).toBe("Manual filesystem corrections");
    expect(await f.files.application().queries.detail("project-1", id)).toEqual(before);
    expect((await f.files.application().navigation.tree("project-1")).nodes).toHaveLength(1);
  } finally {
    await f.close();
  }
}, 60000);

test("a follow-up from an older writing round updates the current document and the same current file", async () => {
  const f = await creationAppFixture();
  let round = 0;
  try {
    f.onRun(async (_input, callbacks, scope) => {
      await f.save(callbacks, scope, "Saved writing round " + ++round);
    });
    const first = await f.create("First document"),
      original = await f.until(first.request.id, (task) => task.state === "succeeded");
    const followUp = async (source: string, prompt: string) => {
      const id = randomUUID();
      expect(
        (await f.files.call("/api/document-creations/message", "POST", { taskId: source, id, prompt })).status,
      ).toBe(202);
      return f.until(id, (task) => task.state === "succeeded" || Boolean(task.failure));
    };
    const second = await followUp(original.id, "Add current details");
    expect(second.state).toBe("succeeded");
    // Simulate a conversation written before the current-file index was introduced.
    await rm(join(f.root, "creation", "exports", "locations"), { recursive: true });
    await f.restart();
    const third = await followUp(original.id, "Add acceptance criteria to the current document");
    expect(third.failure).toBeNull();
    expect(third.state).toBe("succeeded");
    expect(third.artifact?.documentId).toBe(original.artifact?.documentId);
    expect(third.artifact?.file?.path).toBe(original.artifact?.file?.path);
    expect(await readFile(original.artifact!.file!.path, "utf8")).toContain("Saved writing round 3");
    expect((await f.files.application().navigation.tree("project-1")).nodes).toHaveLength(1);
    expect((await readdir(dirname(original.artifact!.file!.path))).filter((name) => name.endsWith(".md"))).toHaveLength(
      1,
    );
  } finally {
    await f.close();
  }
}, 60000);
