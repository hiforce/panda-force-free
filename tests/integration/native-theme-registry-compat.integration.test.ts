import { expect, test } from "bun:test";
import { Database } from "bun:sqlite";
import { mkdtemp, rm } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import legacy from "../fixtures/native-theme-registry-v1.json" with { type: "json" };
import { openNativeThemeDatabase } from "../../src/server/templates/storage/native-database.js";
import { SqliteNativeThemes } from "../../src/server/templates/storage/native-registry.js";
import { openNativeSlidesDatabase } from "../../src/server/slides/storage/registry.js";

const tables = Object.keys(legacy.tables);
function rows(db: Database) {
  return Object.fromEntries(tables.map((table) => [table, db.query(`SELECT * FROM ${table} ORDER BY rowid`).all()]));
}
function schema(db: Database) {
  return db.query("SELECT type,name,tbl_name,sql FROM sqlite_master ORDER BY type,name").all();
}
function seed(path: string) {
  const db = new Database(path, { create: true, strict: true });
  try {
    // This frozen synthetic fixture was generated by the pre-extraction v1 implementation, not the current writer.
    for (const entry of legacy.schema) if (entry.sql && entry.name !== "sqlite_sequence") db.exec(entry.sql);
    const data = legacy.tables as Record<string, Record<string, string | number | null>[]>;
    db.transaction(() => {
      for (const table of tables) {
        db.exec(`DELETE FROM ${table}`);
        for (const row of data[table]!) {
          const columns = Object.keys(row);
          db.query(`INSERT INTO ${table}(${columns.join(",")}) VALUES(${columns.map(() => "?").join(",")})`).run(
            ...Object.values(row),
          );
        }
      }
      db.exec("PRAGMA user_version=1");
    })();
  } finally {
    db.close();
  }
}

test("opening a pre-extraction native-theme registry preserves every schema entry, row, receipt and actor projection", async () => {
  const root = await mkdtemp(join(tmpdir(), "panda-native-ledger-v1-")),
    path = join(root, "native.sqlite");
  try {
    seed(path);
    expect(() => openNativeSlidesDatabase(path)).toThrow("unavailable");
    const db = openNativeThemeDatabase(path);
    try {
      const registry = new SqliteNativeThemes(db);
      expect(schema(db)).toEqual(legacy.schema);
      expect(rows(db)).toEqual(legacy.tables);
      for (const actor of ["owner", "other", "stranger"] as const)
        expect<unknown>(registry.snapshot(actor)).toEqual(legacy.expected[actor]);
      for (const operation of legacy.expected.operations)
        expect<unknown>(registry.operation("owner", operation.operationId)).toEqual(operation);
      expect<unknown>(registry.recoverable()).toEqual(legacy.expected.recoverable);
      expect(registry.source("owner", "example.native", "2.0.0")).toEqual(legacy.expected.source);
      expect(() => registry.detail("stranger", "example.native", "1.0.0")).toThrow("notFound");
      expect(db.query("PRAGMA foreign_key_check").all()).toEqual([]);
      expect(rows(db)).toEqual(legacy.tables);
    } finally {
      db.close();
    }
  } finally {
    await rm(root, { recursive: true, force: true });
  }
});

test("an accepted v1 install completes after upgrade without changing old receipts, defaults or another actor", async () => {
  const root = await mkdtemp(join(tmpdir(), "panda-native-ledger-resume-")),
    path = join(root, "native.sqlite"),
    pending = legacy.expected.operations.find((operation) => operation.state === "pending")!;
  let db: Database | undefined;
  try {
    seed(path);
    db = openNativeThemeDatabase(path);
    const registry = new SqliteNativeThemes(db, () => 1700000010000),
      receipt = registry.commit("owner", pending.operationId, {
        id: "20000000-0000-4000-8000-000000000001",
        digest: legacy.expected.source.digest,
      });
    expect(receipt).toMatchObject({ status: "installed", version: "3.0.0", revision: 5 });
    expect(registry.snapshot("owner").themes.find((theme) => theme.active)!.version).toBe("2.0.0");
    expect<unknown>(registry.snapshot("other")).toEqual(legacy.expected.other);
    expect<unknown>(registry.operation("owner", legacy.expected.operations[0]!.operationId)).toEqual(
      legacy.expected.operations[0],
    );
    expect(() => registry.state("owner", receipt.id, receipt.version, receipt.digest, "activate", 4)).toThrow(
      "conflict",
    );
    db.close();
    db = openNativeThemeDatabase(path);
    const reopened = new SqliteNativeThemes(db);
    expect(reopened.operation("owner", pending.operationId)!.receipt).toEqual(receipt);
    expect<unknown>(reopened.snapshot("other")).toEqual(legacy.expected.other);
    expect(schema(db)).toEqual(legacy.schema);
    expect(db.query("PRAGMA integrity_check").get()).toEqual({ integrity_check: "ok" });
  } finally {
    db?.close();
    await rm(root, { recursive: true, force: true });
  }
});
