import { localizeAttribute, localizeText, setOpaqueAttribute, setOpaqueText } from "../i18n.js";

import { threadInputErrorMessage } from "../../shared/bridge-errors.js";

// Owns the session details view and explicit rename/copy actions.
export function assembleDetails({
  sessions,
  transportPort,
  viewUpdates,
  mutations,
  t,
  state,
  $,
  modelsPort,
  clipboardPort,
  noticesPort,
}) {
  function sessionMarker(id) {
    return id ? `${id.slice(0, 12)}…` : t("workbench.noActiveSession");
  }
  function sessionModelDetails(thread = state.active) {
    const id = thread?.id,
      session = id && state.sessionSettings.get(id),
      modelId = thread?.model || session?.model || "",
      catalog = state.models.find((item) => item.model === modelId),
      label = modelId ? (catalog ? modelsPort.modelDisplay(catalog) : modelId) : t("workbench.modelUnavailable"),
      effort = thread?.reasoningEffort || session?.effort || "";
    return { label, modelId, effort };
  }
  function syncSummaryPanel() {
    const workspace = state.projectless ? "No project" : $("#projectName").textContent || "Local workspace",
      id = state.active?.id || "",
      marker = $("#summarySessionMarker"),
      copy = $("#copySummarySessionMarker"),
      name = $("#summarySessionName"),
      save = $("#saveSummarySessionName"),
      model = $("#summarySessionModel"),
      effortEl = $("#summarySessionEffort"),
      details = sessionModelDetails();
    setOpaqueText($("#summaryWorkspace"), workspace);
    setOpaqueText(
      $("#summaryBranch"),
      state.projectless ? "" : state.active?.source === "remote" ? "Remote workspace" : "Local workspace",
    );
    if ($("#summarySessionTitle")) localizeText($("#summarySessionTitle"), "common.session", undefined, t);
    if ($("#summarySessionHelp"))
      localizeText($("#summarySessionHelp"), "common.sendThisMarkerWhenReportingASessionProblem", undefined, t);
    if (marker) {
      setOpaqueText(marker, sessionMarker(id));
      setOpaqueAttribute(marker, "title", id || t("workbench.noActiveSession"));
      marker.dataset.sessionId = id;
    }
    if (copy) {
      copy.disabled = !id;
      localizeAttribute(copy, "title", "common.copySessionMarker", undefined, t);
      localizeAttribute(copy, "aria-label", "common.copySessionMarker", undefined, t);
    }
    if (model) {
      setOpaqueText(model, details.label);
      setOpaqueAttribute(model, "title", details.modelId || t("workbench.modelUnavailable"));
    }
    if (effortEl) setOpaqueText(effortEl, details.effort ? modelsPort.reasoningLabel(details.effort) : "");
    if (name) {
      if (document.activeElement !== name) name.value = state.active?.name || "";
      name.disabled = !id;
      localizeAttribute(name, "placeholder", "common.autoGeneratedFromFirstMessage", undefined, t);
    }
    if (save) {
      save.disabled = !id;
      localizeText(save, "workbench.saveSessionName", undefined, t);
    }
  }
  async function copySummarySessionMarker() {
    const id = state.active?.id;
    if (!id) return;
    try {
      await clipboardPort.copyMessageText(id);
      noticesPort.toast(t("workbench.sessionMarkerCopied"));
    } catch {
      noticesPort.addPersistentError(t("workbench.copyFailedPleaseSelectAndCopyTheMessageManually"));
    }
  }
  async function renameActiveSession() {
    const threadId = state.active?.id,
      input = $("#summarySessionName"),
      button = $("#saveSummarySessionName"),
      name = input?.value.trim();
    if (!threadId || !input) return;
    if (!name) {
      noticesPort.addPersistentError(t("workbench.sessionNameCannotBeEmpty"));
      input.focus();
      return;
    }
    button.disabled = true;
    try {
      const result = await transportPort.rpc("thread/name/set", { threadId, name });
      if (state.active?.id === threadId)
        mutations.edit("active", (record) => (record.name = result?.thread?.name || name));
      const thread = state.threads.find((item) => item.id === threadId);
      if (thread) sessions.upsertSummary({ id: threadId, name: result?.thread?.name || name });
      viewUpdates.request("sidebar");
      viewUpdates.request("header");
      syncSummaryPanel();
      noticesPort.toast(t("workbench.sessionRenamed"));
    } catch (error) {
      noticesPort.addPersistentError(threadInputErrorMessage(error));
    } finally {
      syncSummaryPanel();
    }
  }
  function bind() {
    $("#copySummarySessionMarker").onclick = (...args) => copySummarySessionMarker(...args);
    $("#saveSummarySessionName").onclick = (...args) => renameActiveSession(...args);
    $("#summarySessionName").onkeydown = (event) => {
      if (event.key === "Enter") {
        event.preventDefault();
        renameActiveSession();
      }
    };
  }
  return {
    bind,
    syncSummaryPanel,
  };
}
