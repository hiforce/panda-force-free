import { join } from "node:path";
import type { BuildInput } from "../../shared/builds/contracts.js";
import type { EngineWorkspace } from "./workspace.js";
import { siteThemeCss } from "../theme.js";
import { body } from "./source.js";
export async function prepareDocusaurus(input: BuildInput, workspace: EngineWorkspace) {
  const { root, toolchain, put, installed } = workspace;
  await put("package.json", JSON.stringify({ name: "panda-document-build", private: true }));
  await put(
    "docusaurus.config.js",
    "module.exports=" +
      JSON.stringify({
        title: input.site.title,
        url: input.site.url,
        baseUrl: input.site.basePath,
        onBrokenLinks: "throw",
        i18n: { defaultLocale: input.site.locale, locales: [input.site.locale] },
        presets: [
          [
            "@docusaurus/preset-classic",
            {
              docs: { routeBasePath: "/", sidebarPath: "./sidebars.js" },
              blog: false,
              ...(input.theme?.schema === 1 ? { theme: { customCss: "./src/css/panda-theme.css" } } : {}),
            },
          ],
        ],
        ...(installed?.entry ? { themes: [installed.entry] } : {}),
        themeConfig: { navbar: { title: input.site.title, items: [] }, colorMode: { respectPrefersColorScheme: true } },
      }) +
      ";",
  );
  if (input.theme?.schema === 1) await put("src/css/panda-theme.css", siteThemeCss(input));
  await put("sidebars.js", "module.exports={handbook:[{type:'autogenerated',dirName:'.'}]};");
  for (const [index, document] of input.documents.entries())
    await put(
      `docs/${document.path}`,
      `---\ntitle: ${JSON.stringify(document.title)}\n${index === 0 ? "slug: /\n" : ""}---\n\n${body(document.content)}`,
    );
  return {
    command: join(toolchain, "node_modules/@docusaurus/core/bin/docusaurus.mjs"),
    args: ["build", root, "--out-dir", join(root, "public")],
    output: join(root, "public"),
  };
}
