import { syncCatalogModules } from "./catalog-modules.mjs";
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { parse as parseJavaScript } from "acorn";
import { SUPPORTED_LOCALES } from "../../src/shared/i18n/locale-policy.js";
import { messageContract } from "../../src/shared/i18n/message-contract.js";

syncCatalogModules(process.argv.includes("--write"));
const failures = [],
  catalogs = new Map();
const files = (directory) =>
  readdirSync(directory, { withFileTypes: true }).flatMap((entry) =>
    entry.isDirectory() ? files(directory + "/" + entry.name) : [directory + "/" + entry.name],
  );
for (const locale of SUPPORTED_LOCALES) {
  const directory = `src/shared/i18n/locales/${locale.code}`,
    all = {};
  for (const path of files(directory)
    .filter((path) => path.endsWith(".json"))
    .sort()) {
    const source = readFileSync(path, "utf8"),
      name = path.split("/").at(-1).slice(0, -5);
    const object = parseJavaScript("(" + source + ")", { ecmaVersion: "latest" }).body[0].expression;
    const keys = new Set();
    for (const property of object.properties) {
      const key = property.key.value || property.key.name;
      if (keys.has(key)) failures.push(path + ": duplicate key " + key);
      keys.add(key);
    }
    for (const [key, text] of Object.entries(JSON.parse(source))) {
      const id = name + "." + key;
      try {
        all[id] = { text, contract: messageContract(text) };
      } catch (error) {
        failures.push(id + " (" + locale.code + "): " + error.message);
      }
    }
  }
  catalogs.set(locale.code, all);
}
const english = catalogs.get("en"),
  namespaces = new Set(Object.keys(english).map((id) => id.split(".")[0]));
for (const [locale, messages] of catalogs) {
  for (const id of Object.keys(english)) {
    if (!messages[id]) failures.push(locale + ": missing " + id);
    else if (JSON.stringify(messages[id].contract) !== JSON.stringify(english[id].contract))
      failures.push(locale + ": parameter contract differs for " + id);
  }
  for (const id of Object.keys(messages)) if (!english[id]) failures.push(locale + ": unknown key " + id);
}
function checkId(id, path) {
  if (typeof id === "string" && /^[a-z]+\.[a-zA-Z0-9]+$/.test(id) && namespaces.has(id.split(".")[0]) && !english[id])
    failures.push(path + ": unknown message ID " + id);
}
function visit(node, path) {
  const positions = { t: 0, translate: 0, localizeText: 1, localizeAttribute: 2, messageHtml: 0, messageAttributes: 1 };
  if (
    node.type === "CallExpression" &&
    node.callee.type === "Identifier" &&
    Object.hasOwn(positions, node.callee.name)
  ) {
    const id = node.arguments[positions[node.callee.name]];
    if (id?.type === "Literal" && typeof id.value === "string" && !english[id.value] && !id.value.startsWith("plugin."))
      failures.push(path + ": translation calls must use registered message IDs: " + id.value);
    if (id?.type === "Literal" && english[id.value]) {
      const required = Object.keys(english[id.value].contract),
        values = node.arguments[positions[node.callee.name] + 1];
      if (required.length && (!values || (values.type === "Identifier" && values.name === "undefined")))
        failures.push(path + ": missing parameters for " + id.value + ": " + required.join(", "));
      else if (
        values?.type === "ObjectExpression" &&
        !values.properties.some((property) => property.type === "SpreadElement")
      ) {
        const supplied = values.properties.map((property) => property.key.name || property.key.value);
        const missing = required.filter((key) => !supplied.includes(key));
        if (missing.length) failures.push(path + ": missing parameters for " + id.value + ": " + missing.join(", "));
      }
    }
  }
  if (node.type === "Literal") checkId(node.value, path);
  if (node.type === "TemplateElement" || node.type === "Literal") {
    const text = node.type === "TemplateElement" ? node.value.raw : node.value;
    if (typeof text === "string")
      for (const match of text.matchAll(/data-pf-(?:message|title|placeholder|aria-label)=["']([^"']+)["']/g))
        checkId(match[1], path);
  }
  for (const value of Object.values(node)) {
    if (Array.isArray(value)) value.forEach((entry) => entry?.type && visit(entry, path));
    else if (value?.type) visit(value, path);
  }
}
for (const path of [...files("src/client"), "src/shared/codex-surfaces.js"].filter((path) => path.endsWith(".js")))
  visit(parseJavaScript(readFileSync(path, "utf8"), { ecmaVersion: "latest", sourceType: "module" }), path);
for (const match of readFileSync("public/index.html", "utf8").matchAll(
  /data-pf-(?:message|title|placeholder|aria-label)="([^"]+)"/g,
))
  checkId(match[1], "public/index.html");
const declaration =
  "// Generated by scripts/i18n/validate.mjs --write. Do not edit manually.\n" +
  "export interface MessageParameters {\n" +
  Object.entries(english)
    .sort(([left], [right]) => left.localeCompare(right))
    .map(
      ([id, { contract }]) =>
        `  ${JSON.stringify(id)}: { ${Object.entries(contract)
          .map(([key, type]) => `${JSON.stringify(key)}: ${type === "date" ? "Date | number" : type}`)
          .join("; ")} };`,
    )
    .join("\n") +
  "\n}\nexport type MessageId = keyof MessageParameters;\nexport type Translate = <K extends MessageId>(id: K, ...values: keyof MessageParameters[K] extends never ? [values?: MessageParameters[K]] : [values: MessageParameters[K]]) => string;\n";
const typesPath = "src/shared/i18n/messages.d.ts";
if (process.argv.includes("--write")) writeFileSync(typesPath, declaration);
else {
  try {
    if (readFileSync(typesPath, "utf8") !== declaration)
      failures.push("Message types are stale; run bun scripts/i18n/validate.mjs --write");
  } catch {
    failures.push("Generated message types are missing");
  }
}
if (failures.length) {
  console.error([...new Set(failures)].join("\n"));
  process.exit(1);
}
console.log(
  `Validated ${Object.keys(english).length} message contracts, source IDs and generated types across ${catalogs.size} published locales.`,
);
