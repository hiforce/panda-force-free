import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { SUPPORTED_LOCALES } from "../../src/shared/i18n/locale-policy.js";

const header = "// Generated by scripts/i18n/validate.mjs --write. Do not edit manually.\n";
export function catalogModules() {
  const domains = readdirSync("src/shared/i18n/locales/en")
    .filter((name) => name.endsWith(".json"))
    .sort();
  const imports = (locale, index) =>
    domains.map((name, domain) => `import m${index}_${domain} from "./locales/${locale}/${name}";`).join("\n");
  const entries = (index, indent = "  ") =>
    domains.map((name, domain) => `${indent}${JSON.stringify(name.slice(0, -5))}: m${index}_${domain},`).join("\n");
  return {
    "src/shared/i18n/catalogs.js":
      header + imports("en", 0) + "\nexport const englishMessages = {\n" + entries(0) + "\n};\n",
    "src/shared/i18n/server-catalogs.js":
      header +
      SUPPORTED_LOCALES.filter((entry) => entry.code !== "en")
        .map((entry, index) => imports(entry.code, index))
        .join("\n") +
      "\nexport const serverMessages = {\n" +
      SUPPORTED_LOCALES.filter((entry) => entry.code !== "en")
        .map((entry, index) => `  ${JSON.stringify(entry.code)}: {\n${entries(index, "    ")}\n  },`)
        .join("\n") +
      "\n};\n",
  };
}
export function syncCatalogModules(write = false) {
  for (const [path, content] of Object.entries(catalogModules())) {
    if (write) writeFileSync(path, content);
    else if (readFileSync(path, "utf8") !== content)
      throw new Error("Catalog indexes are stale; run bun scripts/i18n/validate.mjs --write");
  }
}
